import { test, expect } from '@playwright/test';

test('public literature workflow saves a global draft, tags it, registers and previews', async ({ page }, info) => {
  const management: string[] = [];
  const errors: string[] = [];
  page.on('request', (request) => { if (/\/api\/(literature|eval)(\/|$)/.test(new URL(request.url()).pathname)) management.push(request.url()); });
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/showcase');
  await page.getByRole('link', { name: '体验文献管理', exact: true }).click();
  await expect(page.getByText('展示模式 · 流程体验')).toBeVisible();
  await expect(page.getByRole('status')).toHaveText('共 2 条示例文献');
  await page.getByRole('link', { name: '体验登记流程' }).click();
  await expect(page.getByRole('button', { name: '下一步', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '载入示例 PDF' }).click();
  await page.getByRole('button', { name: '保存示例草稿' }).click();
  await expect(page.getByRole('heading', { name: '文献流程示例（待整理）', exact: true })).toBeVisible();
  const detailUrl = page.url();
  await expect(page.getByText('未打标（全局）。可逐篇补充分类，不影响默认列表可见性。')).toBeVisible();
  await page.getByRole('button', { name: '继续整理与打标' }).click();
  await page.getByRole('button', { name: '下一步', exact: true }).click();
  await page.getByRole('button', { name: '完成示例登记' }).click();
  await expect(page.getByRole('main').getByRole('alert')).toContainText('请补充标题');
  await page.getByRole('button', { name: '填入示例信息' }).click();
  await page.getByRole('button', { name: '下一步', exact: true }).click();
  await page.getByRole('button', { name: '主题领域级联选择' }).click();
  await page.getByRole('checkbox', { name: '水氮管理', exact: true }).check();
  await page.getByRole('button', { name: '展开 水氮管理', exact: true }).click();
  await page.getByRole('checkbox', { name: '水氮管理 / 氮素淋失', exact: true }).check();
  await expect(page.getByRole('checkbox', { name: '水氮管理', exact: true })).not.toBeChecked();
  await page.getByRole('button', { name: '完成选择' }).click();
  await page.getByRole('button', { name: '研究对象级联选择' }).click();
  await page.getByRole('checkbox', { name: '冬小麦', exact: true }).check();
  await page.getByRole('button', { name: '完成选择' }).click();
  await page.getByRole('button', { name: '完成示例登记' }).click();
  await expect(page.getByRole('heading', { name: '农田水氮管理研究（流程示例）', exact: true })).toBeVisible();
  await expect(page.getByText('体验操作 · 完成登记 · 已选 2 个标签')).toBeVisible();
  await page.getByRole('button', { name: '预览示例 PDF' }).click();
  await expect(page.getByTitle('示例 PDF 预览')).toBeVisible();
  const pdf = await page.request.get('/showcase-assets/literature-workflow-sample.pdf');
  expect(pdf.status()).toBe(200);
  expect((await pdf.body()).subarray(0, 5).toString()).toBe('%PDF-');
  await page.getByRole('button', { name: '关闭预览' }).click();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('link', { name: '下载示例 PDF' }).click();
  expect((await downloaded).suggestedFilename()).toBe('literature-workflow-sample.pdf');
  await page.screenshot({ path: info.outputPath('registered-showcase.png'), fullPage: true });
  await page.getByRole('link', { name: '水氮管理 / 氮素淋失', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('共 2 条示例文献');
  await page.getByRole('link', { name: '农田水氮管理研究（流程示例）', exact: true }).click();
  await expect(page).toHaveURL(detailUrl);
  await page.reload();
  await expect(page.getByRole('heading', { name: '示例不存在或已重置' })).toBeVisible();
  expect(management).toEqual([]);
  expect(errors).toEqual([]);
});

test('public taxonomy links descendants and preserves newly added tags across modules', async ({ page }) => {
  await page.goto('/showcase/literature-tags');
  await page.getByRole('button', { name: '在 水氮管理 下新增标签' }).click();
  await page.getByLabel('新标签名称', { exact: true }).fill('灌溉管理');
  await page.getByRole('button', { name: '保存标签', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('示例标签已添加');
  await page.getByRole('button', { name: '在 水氮管理 下新增标签' }).click();
  await page.getByLabel('新标签名称', { exact: true }).fill('灌溉管理');
  await page.getByRole('button', { name: '保存标签', exact: true }).click();
  await expect(page.getByRole('main').getByRole('alert')).toContainText('不能有重名');
  await page.getByRole('listitem').filter({ has: page.getByText('水氮管理', { exact: true }) }).getByRole('link', { name: '关联文献 2 篇' }).click();
  await expect(page.getByRole('status')).toHaveText('共 2 条示例文献');
  await page.getByRole('link', { name: '水稻养分利用效率研究（流程示例）', exact: true }).click();
  await page.getByRole('button', { name: '继续整理与打标' }).click();
  await page.getByRole('button', { name: '下一步', exact: true }).click();
  await page.getByRole('button', { name: '主题领域级联选择' }).click();
  await page.getByRole('button', { name: '展开 水氮管理', exact: true }).click();
  await page.getByRole('checkbox', { name: '水氮管理 / 灌溉管理', exact: true }).check();
  await page.getByRole('button', { name: '完成选择' }).click();
  await page.getByRole('button', { name: '保存示例修改' }).click();
  await expect(page.getByText('已停用', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '恢复示例文献' }).click();
  await page.getByRole('link', { name: '返回文献管理', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('共 3 条示例文献');
  page.once('dialog', (dialog) => dialog.accept());
  await page.getByRole('button', { name: '重置示例' }).click();
  await expect(page.getByRole('status')).toHaveText('共 2 条示例文献');
});

test('mobile literature remains usable without the public catalog service', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.route('**/api/demo/catalog', (route) => route.abort());
  await page.goto('/showcase/literature');
  await expect(page.getByRole('heading', { name: '文献管理', exact: true })).toBeVisible();
  await page.getByLabel('搜索示例文献').fill('不存在的示例');
  await expect(page.getByRole('status')).toHaveText('共 0 条示例文献');
  await page.getByRole('button', { name: '重置筛选' }).click();
  await expect(page.getByRole('status')).toHaveText('共 2 条示例文献');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('literature-mobile.png'), fullPage: true });
  await page.getByRole('navigation', { name: '移动端展示导航' }).getByRole('link', { name: '标签管理', exact: true }).click();
  await expect(page.getByRole('heading', { name: '标签管理', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('link', { name: '返回文献并打标' }).click();
  await page.getByRole('link', { name: '体验登记流程' }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
