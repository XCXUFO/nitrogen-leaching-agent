import { test, expect } from '@playwright/test';

test('isolated live backend: baseline, replay, comparison and independent scoring', async ({ page }) => {
  test.skip(!process.env.EVAL_TEST_API, 'Requires the isolated evaluation test backend, never the shared review database.');
  const api = process.env.EVAL_TEST_API!;
  const errors: string[] = []; page.on('pageerror', (e) => errors.push(e.message));
  await page.route('**/api/eval/**', async (route) => {
    const url = new URL(route.request().url());
    const response = await route.fetch({ url: `${api}${url.pathname}${url.search}` });
    await route.fulfill({ response, headers: { ...response.headers(), 'access-control-allow-origin': '*' } });
  });
  await page.goto('/evaluation/tasks/new');
  await page.getByLabel('评测访问密钥').fill('browser-test-developer-token-0000000000000000');
  await page.getByRole('button', { name: '进入工作台' }).click();
  await page.getByLabel('任务用例 NEW01@2').check();
  await page.getByLabel('任务标题').fill(`browser task ${Date.now()}`);
  await page.getByLabel('构建版本').fill('browser-workflow-20261003');
  await page.getByLabel('知识库版本').fill('no-rag-test');
  await page.getByRole('button', { name: '创建任务' }).click();
  await page.getByRole('button', { name: '批量准备我的执行' }).click();
  await page.getByLabel('任务详情').getByRole('button', { name: /打开执行/ }).click();
  await page.getByRole('button', { name: '重置上下文' }).click();
  await page.getByLabel('执行问题').fill('1');
  await page.getByRole('button', { name: '发送本轮' }).click();
  await expect(page.getByRole('button', { name: '复制回答' })).toHaveCount(1);
  await page.getByLabel('执行问题').fill('你好');
  await page.getByRole('button', { name: '发送本轮' }).click();
  await expect(page.getByRole('button', { name: '复制回答' })).toHaveCount(2);
  await page.getByLabel('总体结论').selectOption('fail');
  await page.getByLabel('路由是否正确').selectOption('yes');
  await page.getByLabel('工具使用是否正确').selectOption('n.a.');
  await page.getByLabel('证据是否支持').selectOption('n.a.');
  await page.getByLabel('答案是否正确').selectOption('no');
  await page.getByLabel('评分说明').fill('SYNTHETIC failure for isolated issue workflow test only.');
  await page.getByRole('button', { name: '提交并冻结评分' }).click();
  await expect(page.getByRole('heading', { name: '已保存的开发试评' })).toBeVisible();
  const baselineExecutionUrl = page.url();
  await page.getByRole('link', { name: '登记问题 / 关联复测' }).click();
  const issueTitle = `BROWSER TEST ONLY: issue ${Date.now()}`;
  await page.getByLabel('问题轮次').selectOption((await page.getByLabel('问题轮次').locator('option').nth(1).getAttribute('value'))!);
  await page.getByLabel('问题标题').fill(issueTitle);
  await page.getByLabel('负责人', { exact: true }).fill('browser-test-developer');
  await page.getByLabel('问题证据').fill('Synthetic test of preserving the original Run and independent reviews.');
  await page.getByRole('button', { name: '登记问题' }).click();
  await expect(page.getByRole('article', { name: `问题：${issueTitle}`, exact: true })).toBeVisible();
  await page.getByRole('link', { name: '查看执行与证据' }).click();
  await page.getByRole('link', { name: '保存基线 / 回归对比' }).click();
  const title = `BROWSER TEST ONLY: capability flow ${Date.now()}`;
  await page.getByLabel('回归基线标题').fill(title);
  await page.getByRole('button', { name: '保存为回归基线' }).click();
  const card = page.locator('article').filter({ hasText: title });
  await card.getByRole('button', { name: '用当前版本重跑' }).click();
  await expect(card.getByRole('button', { name: '比较结果' }).first()).toBeVisible({ timeout: 30000 });
  await card.getByRole('button', { name: '比较结果' }).first().click();
  await expect(page.getByRole('region', { name: '版本比较结果' })).toContainText('0 轮存在内容或配置变化');
  await expect(page.getByText('冻结基线', { exact: true })).toHaveCount(2);
  await card.getByRole('button', { name: '打开新执行 / 人工评分' }).first().click();
  await page.getByRole('button', { name: '提交并冻结评分' }).click();
  await expect(page.getByRole('alert').filter({ hasText: '请先选择：总体结论' })).toBeVisible();
  await page.getByLabel('总体结论').selectOption('pass');
  await page.getByLabel('路由是否正确').selectOption('yes');
  await page.getByLabel('工具使用是否正确').selectOption('n.a.');
  await page.getByLabel('证据是否支持').selectOption('n.a.');
  await page.getByLabel('答案是否正确').selectOption('yes');
  await page.getByLabel('评分说明').fill('AUTOMATED BROWSER TEST ONLY; synthetic evaluation database; not a professional review.');
  await page.getByRole('button', { name: '提交并冻结评分' }).click();
  await expect(page.getByRole('heading', { name: '已保存的开发试评' })).toBeVisible();
  await expect(page.getByRole('button', { name: '提交并冻结评分' })).toHaveCount(0);
  const retestExecutionUrl = page.url();
  await page.getByRole('link', { name: '登记问题 / 关联复测' }).click();
  const issueOption = page.getByLabel('待复测问题').locator('option').filter({ hasText: issueTitle });
  await page.getByLabel('待复测问题').selectOption((await issueOption.getAttribute('value'))!);
  await expect(page.getByLabel('修复版本')).toHaveValue('browser-workflow-20261003');
  await page.getByRole('button', { name: '保存复测关联' }).click();
  const issueCard = page.getByRole('article', { name: `问题：${issueTitle}`, exact: true });
  await expect(issueCard).toContainText('复测 1 次');
  await expect(issueCard).toContainText('版本已核验');
  await issueCard.getByRole('button', { name: '打开原执行与证据' }).click();
  await expect(page.getByRole('heading', { name: '已保存的开发试评' }).locator('..')).toContainText('总体结论：不通过');
  await page.goBack();
  await issueCard.getByRole('button', { name: '打开复测执行与评分' }).click();
  await expect(page).toHaveURL(retestExecutionUrl);
  expect(baselineExecutionUrl).not.toBe(retestExecutionUrl);
  await expect(page.getByRole('heading', { name: '已保存的开发试评' }).locator('..')).toContainText('总体结论：通过');
  expect(errors).toEqual([]);
  await page.screenshot({ path: '/tmp/nitrogen-browser-evaluation.png', fullPage: true });
});
